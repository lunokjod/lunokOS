#!/usr/bin/env python3
# =============================================================================
#  lunokOS :: tools/gen_about.py
# =============================================================================
#  Writes the list of libraries the About page shows, from the tree itself.
#
#  WHY IT IS DATA AND NOT A LUA CHUNK
#  ----------------------------------
#  The paper project's version of this wrote a `libs.lua` and the app ran it with
#  `files.load`. An app here cannot run a file: `dofile`, `loadfile` and `load`
#  are **removed from its state** on purpose (docs/20, docs/30), so the list is
#  written as lines of data and parsed where it is read. It is also cheaper: a
#  chunk is compiled and a table of five fields a line is cut with one pattern.
#
#  The format, one library a line and a tab between fields, the description to the
#  end of the line (so a description may hold anything but a tab and a break):
#
#     name \t version \t dir \t license \t what
#
#  Usage:
#     tools/gen_about.py                     # writes apps/about/res/libs.txt
#     tools/gen_about.py --check             # says whether it is up to date
# =============================================================================

import argparse
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
# **Where the app reads it**: the app's own `res/`, which is `/res` while it runs
# (docs/70). The master is `libs.txt` and the app is the only reader.
OUT = os.path.join(ROOT, "apps", "about", "res", "libs.txt")

HEADER = """# Generated by `tools/gen_about.py` from the `library.json` of every folder of `lib/`.
# Do not edit by hand: run the tool (docs/45). This file is what the About page lists.
# name<TAB>version<TAB>dir<TAB>license<TAB>what
"""


def field(text):
    """A field of a line: no tab and no break can be inside one."""
    return " ".join(str(text).replace("\t", " ").splitlines())


def libraries():
    """Every library of `lib/`, in the order of its name, or a failure."""
    found = []
    missing = []

    for folder in sorted(glob.glob(os.path.join(ROOT, "lib", "*"))):
        if not os.path.isdir(folder):
            continue
        manifest = os.path.join(folder, "library.json")
        name = os.path.basename(folder)
        if not os.path.exists(manifest):
            missing.append(name)
            continue
        with open(manifest, "r", encoding="utf-8") as handle:
            data = json.load(handle)
        found.append({
            "name": data.get("name", name),
            "version": data.get("version", ""),
            "dir": "lib/" + name,
            "license": data.get("license", ""),
            "what": data.get("description", ""),
        })

    if missing:
        sys.stderr.write("These folders of lib/ carry no library.json: %s\n" % ", ".join(missing))
        sys.stderr.write("A library that does not say who it is cannot be listed (docs/45).\n")
        sys.exit(1)

    found.sort(key=lambda item: item["name"])
    return found


def render(items):
    """The whole file, as the app reads it."""
    text = HEADER
    for item in items:
        text += "\t".join(field(item[key]) for key in ("name", "version", "dir", "license", "what")) + "\n"
    return text


def main():
    parser = argparse.ArgumentParser(description="The list of libraries the About page shows")
    parser.add_argument("--check", action="store_true",
                        help="do not write: say whether the file is up to date")
    args = parser.parse_args()

    items = libraries()
    text = render(items)

    if args.check:
        try:
            with open(OUT, "r", encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            sys.stderr.write("%s does not exist: run tools/gen_about.py\n" % OUT)
            sys.exit(1)
        if current != text:
            sys.stderr.write("%s is out of date: run tools/gen_about.py\n" % OUT)
            sys.exit(1)
        print("%s is up to date: %d libraries" % (OUT, len(items)))
        return

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("%s: %d libraries, %d bytes" % (OUT, len(items), len(text.encode("utf-8"))))


main()
